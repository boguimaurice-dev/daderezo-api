-- A appliquer avant le code correspondant. Tables internes, jamais exposées aux rôles client.
CREATE TABLE IF NOT EXISTS public.platform_applications (
 id text PRIMARY KEY, identity_id text NOT NULL UNIQUE, email text NOT NULL,
 org_name text NOT NULL, contact_name text NOT NULL, site_description text NOT NULL,
 authorization_confirmed integer NOT NULL, status text NOT NULL, payment_status text NOT NULL,
 created_at text NOT NULL, updated_at text NOT NULL, org_slug text UNIQUE, probe_api_key text UNIQUE, subscription_end text
);
CREATE TABLE IF NOT EXISTS public.platform_admin_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ts text NOT NULL,
 actor text NOT NULL, application_id text NOT NULL, action text NOT NULL, details text NOT NULL
);
ALTER TABLE public.platform_applications ADD COLUMN IF NOT EXISTS org_slug text;
ALTER TABLE public.platform_applications ADD COLUMN IF NOT EXISTS probe_api_key text;
ALTER TABLE public.platform_applications ADD COLUMN IF NOT EXISTS subscription_end text;
CREATE UNIQUE INDEX IF NOT EXISTS platform_application_org_idx ON public.platform_applications(org_slug);
CREATE UNIQUE INDEX IF NOT EXISTS platform_application_probe_idx ON public.platform_applications(probe_api_key);
ALTER TABLE public.platform_applications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.platform_admin_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.platform_applications, public.platform_admin_events FROM anon, authenticated;
CREATE OR REPLACE FUNCTION public.decide_platform_application(p_id text, p_status text, p_payment text, p_actor text, p_ts text, p_subscription_end text)
RETURNS SETOF public.platform_applications LANGUAGE plpgsql SECURITY INVOKER SET search_path = public AS $$
BEGIN
 UPDATE public.platform_applications SET status=p_status, payment_status=p_payment, updated_at=p_ts, subscription_end=p_subscription_end WHERE id=p_id;
 IF FOUND THEN
   INSERT INTO public.platform_admin_events(ts, actor, application_id, action, details)
   VALUES(p_ts, p_actor, p_id, 'decision', json_build_object('status',p_status,'payment_status',p_payment,'subscription_end',p_subscription_end)::text);
   RETURN QUERY SELECT * FROM public.platform_applications WHERE id=p_id;
 END IF;
END $$;
REVOKE ALL ON FUNCTION public.decide_platform_application(text,text,text,text,text,text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.decide_platform_application(text,text,text,text,text,text) TO service_role;
GRANT ALL ON public.platform_applications, public.platform_admin_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.platform_admin_events_id_seq TO service_role;

-- Rattachement ponctuel, après preuve de possession de l'ancien compte côté API.
CREATE OR REPLACE FUNCTION public.claim_legacy_workspace(p_identity text, p_legacy_org text, p_actor text, p_ts text)
RETURNS SETOF public.platform_applications LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $$
DECLARE target public.platform_applications%ROWTYPE;
BEGIN
 SELECT * INTO target FROM public.platform_applications WHERE identity_id=p_identity FOR UPDATE;
 IF NOT FOUND OR target.status <> 'pending' OR target.org_slug = p_legacy_org
    OR EXISTS (SELECT 1 FROM public.platform_admin_events WHERE application_id=target.id)
    OR EXISTS (SELECT 1 FROM public.platform_applications WHERE org_slug=p_legacy_org AND id<>target.id)
    OR EXISTS (SELECT 1 FROM public.agents WHERE org_slug=target.org_slug)
 THEN RETURN; END IF;
 UPDATE public.platform_applications SET org_slug=p_legacy_org, updated_at=p_ts WHERE id=target.id;
 INSERT INTO public.platform_admin_events(ts,actor,application_id,action,details)
 VALUES(p_ts,p_actor,target.id,'legacy_claim',json_build_object('org_slug',p_legacy_org)::text);
 RETURN QUERY SELECT * FROM public.platform_applications WHERE id=target.id;
END $$;
REVOKE ALL ON FUNCTION public.claim_legacy_workspace(text,text,text,text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_legacy_workspace(text,text,text,text) TO service_role;

CREATE OR REPLACE FUNCTION public.upsert_tenant_agent(p_id text,p_nom text,p_ip text,p_mac text,p_ts text,p_org text)
RETURNS TABLE(allowed boolean) LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $$
DECLARE affected integer;
BEGIN
 INSERT INTO public.agents(id,nom,ip,mac,last_seen,status,org_slug)
 VALUES(p_id,p_nom,p_ip,p_mac,p_ts,'online',p_org)
 ON CONFLICT(id) DO UPDATE SET nom=excluded.nom, ip=COALESCE(excluded.ip,agents.ip),
 mac=COALESCE(excluded.mac,agents.mac), last_seen=excluded.last_seen, status=excluded.status
 WHERE COALESCE(agents.org_slug,'public-demo')=p_org;
 GET DIAGNOSTICS affected = ROW_COUNT;
 RETURN QUERY SELECT affected = 1;
END $$;
REVOKE ALL ON FUNCTION public.upsert_tenant_agent(text,text,text,text,text,text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.upsert_tenant_agent(text,text,text,text,text,text) TO service_role;
